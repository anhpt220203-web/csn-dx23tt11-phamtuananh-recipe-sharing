alter table public.categories enable row level security;
alter table public.recipes enable row level security;
alter table public.recipe_ingredients enable row level security;
alter table public.favorites enable row level security;
alter table public.ratings enable row level security;

-- categories / recipes / recipe_ingredients: đọc công khai, chỉ admin được ghi.
-- (Mọi thao tác ghi từ app phải đi qua server với service role + kiểm tra
-- quyền ở phía server theo NFR2.)
create policy categories_read on public.categories
    for select to anon, authenticated using (true);

create policy categories_admin_write on public.categories
    for all to authenticated
    using (kit.is_admin())
    with check (kit.is_admin());

create policy recipes_read on public.recipes
    for select to anon, authenticated using (true);

create policy recipes_admin_write on public.recipes
    for all to authenticated
    using (kit.is_admin())
    with check (kit.is_admin());

create policy recipe_ingredients_read on public.recipe_ingredients
    for select to anon, authenticated using (true);

create policy recipe_ingredients_admin_write on public.recipe_ingredients
    for all to authenticated
    using (kit.is_admin())
    with check (kit.is_admin());

-- favorites: chỉ chủ sở hữu được đọc/ghi của chính mình, admin toàn quyền
create policy favorites_owner_rw on public.favorites
    for all to authenticated
    using (user_id = (select auth.uid()) or kit.is_admin())
    with check (user_id = (select auth.uid()) or kit.is_admin());

-- ratings: đọc công khai (để tính điểm trung bình), chỉ chủ sở hữu được ghi, admin toàn quyền
create policy ratings_read on public.ratings
    for select to anon, authenticated using (true);

create policy ratings_owner_write on public.ratings
    for insert to authenticated
    with check (user_id = (select auth.uid()) or kit.is_admin());

create policy ratings_owner_update on public.ratings
    for update to authenticated
    using (user_id = (select auth.uid()) or kit.is_admin())
    with check (user_id = (select auth.uid()) or kit.is_admin());

create policy ratings_owner_delete on public.ratings
    for delete to authenticated
    using (user_id = (select auth.uid()) or kit.is_admin());

