-- Bảng banners: carousel hero trang chủ (theo review Knorr)
create table if not exists public.banners
(
    id          bigint generated by default as identity primary key,
    title       text not null,
    subtitle    text,
    image_url   text,
    link_url    text,
    sort_order  integer not null default 0,
    is_active   boolean not null default true,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

comment on table public.banners is 'Banner carousel trang chủ';

-- Bảng tips: bài viết mẹo vặt / bí quyết nấu ăn (theo review Knorr)
create table if not exists public.tips
(
    id          bigint generated by default as identity primary key,
    title       text not null,
    slug        text not null unique,
    excerpt     text,
    content     text not null,
    image_url   text,
    is_published boolean not null default false,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

comment on table public.tips is 'Bài viết mẹo vặt nấu ăn';

-- RLS: đọc công khai, ghi qua service role (admin)
alter table public.banners enable row level security;
alter table public.tips enable row level security;

drop policy if exists "banners_public_read" on public.banners;
create policy "banners_public_read"
    on public.banners for select
    using (true);

drop policy if exists "tips_public_read" on public.tips;
create policy "tips_public_read"
    on public.tips for select
    using (is_published = true);
