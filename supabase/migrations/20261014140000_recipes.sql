 * sang Supabase trực tiếp (không Prisma/Better-Auth).
 *
 * Bảng:
 *   - categories           : 7 danh mục món ăn
 *   - recipes              : công thức (1 Category ── N Recipe);
 *                            steps lưu dạng jsonb (mảng các bước),
 *                            status: 'published' | 'draft'
 *   - recipe_ingredients   : nguyên liệu tách bảng riêng (tìm kiếm chính xác),
 *                            khóa chính (recipe_id, position)
 *   - favorites            : món yêu thích (khóa chính kép user_id + recipe_id)
 *   - ratings              : đánh giá 1–5 sao, UNIQUE(user_id, recipe_id)
 *
 * Quyền admin: kiểm tra qua auth.jwt() -> 'app_metadata' ->> 'role' = 'admin'.
 * Tài khoản admin demo được gắn role này theo hướng dẫn ở supabase/seed.sql.
 * -------------------------------------------------------
 */

-- Tìm kiếm nguyên liệu: chỉ mục trigram (tìm chính xác + gần đúng, không dấu)
create extension if not exists "pg_trgm" schema kit;

-- Helper: user hiện tại có phải admin không
create or replace function kit.is_admin() returns boolean
    language plpgsql
    security definer
    set search_path = '' as
$$
begin
    return coalesce(
        (auth.jwt() -> 'app_metadata' ->> 'role'),
        ''
    ) = 'admin';
end;
$$;

grant execute on function kit.is_admin() to anon, authenticated, service_role;

-- Helper: tự động cập nhật updated_at
create or replace function kit.touch_updated_at() returns trigger
    language plpgsql
    set search_path = '' as
$$
begin
    new.updated_at = now();
    return new;
end;
$$;

-- ─── categories ───
create table if not exists public.categories
(
    id          bigint generated by default as identity primary key,
    name        text not null,
    slug        text not null unique,
    description text,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

comment on table public.categories is 'Danh mục món ăn (7 danh mục seed theo spec)';

-- ─── recipes ───
create table if not exists public.recipes
(
    id          bigint generated by default as identity primary key,
    category_id bigint not null references public.categories (id) on delete restrict,
    title       text not null,
    slug        text not null unique,
    description text,
    image_url   text,
    servings    integer,
    cook_time   integer,
    difficulty  text check (difficulty in ('Dễ', 'Trung bình', 'Khó')),
    steps       jsonb not null default '[]'::jsonb,
    status      text not null default 'published' check (status in ('published', 'draft')),
    source_name text,
    source_url  text,
    created_by  uuid references auth.users (id) on delete set null,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

comment on table public.recipes is 'Công thức nấu ăn';
comment on column public.recipes.cook_time is 'Thời gian nấu (phút)';
comment on column public.recipes.steps is 'Các bước thực hiện (mảng JSON)';

-- ─── recipe_ingredients (nguyên liệu tách bảng riêng để tìm kiếm chính xác) ───
create table if not exists public.recipe_ingredients
(
    recipe_id bigint not null references public.recipes (id) on delete cascade,
    position  integer not null,
    name      text not null,
    primary key (recipe_id, position)
);

comment on table public.recipe_ingredients is 'Nguyên liệu của từng công thức, tách bảng riêng để tìm kiếm chính xác';

-- ─── favorites (1 người – 1 lượt yêu thích: khóa chính kép) ───
create table if not exists public.favorites
(
    user_id    uuid not null references auth.users (id) on delete cascade,
    recipe_id  bigint not null references public.recipes (id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (user_id, recipe_id)
);

comment on table public.favorites is 'Món yêu thích của người dùng';

-- ─── ratings (1 người – 1 đánh giá: UNIQUE(user_id, recipe_id)) ───
create table if not exists public.ratings
(
    id         bigint generated by default as identity primary key,
    user_id    uuid not null references auth.users (id) on delete cascade,
    recipe_id  bigint not null references public.recipes (id) on delete cascade,
    rating     smallint not null check (rating between 1 and 5),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (user_id, recipe_id)
);

comment on table public.ratings is 'Đánh giá 1–5 sao, mỗi người 1 lượt mỗi công thức';

-- ─── Chỉ mục ───
create index if not exists recipes_category_id_idx on public.recipes (category_id);
create index if not exists recipes_slug_idx on public.recipes (slug);
create index if not exists recipes_status_idx on public.recipes (status);
create index if not exists recipe_ingredients_recipe_id_idx on public.recipe_ingredients (recipe_id);
create index if not exists favorites_recipe_id_idx on public.favorites (recipe_id);
create index if not exists ratings_recipe_id_idx on public.ratings (recipe_id);

-- Chỉ mục tìm kiếm nguyên liệu (trigram, hỗ trợ không dấu)
-- Xem migration 20261016180000_fix_unaccent_immutable.sql: tạo hàm
-- kit.unaccent_immutable() (IMMUTABLE) rồi tạo index ở đó, vì kit.unaccent
-- của extension là STABLE, không dùng trực tiếp trong index được.

-- ─── Trigger updated_at ───
drop trigger if exists touch_updated_at on public.categories;
create trigger touch_updated_at
    before update on public.categories
    for each row execute function kit.touch_updated_at();

drop trigger if exists touch_updated_at on public.recipes;
create trigger touch_updated_at
    before update on public.recipes
    for each row execute function kit.touch_updated_at();

drop trigger if exists touch_updated_at on public.ratings;
create trigger touch_updated_at
    before update on public.ratings
    for each row execute function kit.touch_updated_at();

