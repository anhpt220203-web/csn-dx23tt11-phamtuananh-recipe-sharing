-- Danh mục nhiều chiều + tags + hỏi đáp (2026-10-16)

-- 1. Chiều danh mục: nhom-mon (mặc định), nguyen-lieu-chinh,
--    phuong-phap-che-bien, bua-an, phong-cach-am-thuc
alter table public.categories
  add column if not exists dimension text not null default 'nhom-mon'
  check (dimension in (
    'nhom-mon',
    'nguyen-lieu-chinh',
    'phuong-phap-che-bien',
    'bua-an',
    'phong-cach-am-thuc'
  ));

comment on column public.categories.dimension is 'Chiều phân loại danh mục';

-- 2. Tags chủ đề ("Tìm món")
create table if not exists public.tags
(
    id          bigint generated by default as identity primary key,
    name        text not null,
    slug        text not null unique,
    created_at  timestamptz not null default now()
);

comment on table public.tags is 'Tag chủ đề món ăn (vd: Món chay, Món ăn sáng)';

create table if not exists public.recipe_tags
(
    recipe_id   bigint not null references public.recipes (id) on delete cascade,
    tag_id      bigint not null references public.tags (id) on delete cascade,
    primary key (recipe_id, tag_id)
);

comment on table public.recipe_tags is 'Gán tag cho công thức';

-- 3. Hỏi đáp công thức
create table if not exists public.recipe_questions
(
    id          bigint generated by default as identity primary key,
    recipe_id   bigint not null references public.recipes (id) on delete cascade,
    user_id     uuid not null references auth.users (id) on delete cascade,
    question    text not null,
    answer      text,
    answered_at timestamptz,
    created_at  timestamptz not null default now()
);

comment on table public.recipe_questions is 'Câu hỏi của user về công thức, admin trả lời';

-- RLS
alter table public.tags enable row level security;
alter table public.recipe_tags enable row level security;
alter table public.recipe_questions enable row level security;

drop policy if exists "tags_public_read" on public.tags;
create policy "tags_public_read"
    on public.tags for select
    using (true);

drop policy if exists "recipe_tags_public_read" on public.recipe_tags;
create policy "recipe_tags_public_read"
    on public.recipe_tags for select
    using (true);

drop policy if exists "questions_public_read" on public.recipe_questions;
create policy "questions_public_read"
    on public.recipe_questions for select
    using (true);

drop policy if exists "questions_user_insert" on public.recipe_questions;
create policy "questions_user_insert"
    on public.recipe_questions for insert
    with check (auth.uid() = user_id);

