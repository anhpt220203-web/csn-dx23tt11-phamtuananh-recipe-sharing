/*
 * -------------------------------------------------------
 * Recipe Sharing — Bảng các bước thực hiện (BLOCKER P0)
 *
 * Không có migration nào tạo bảng public.recipe_steps trước đây,
 * nhưng src/supabase/seed.sql (DELETE/INSERT INTO public.recipe_steps),
 * getRecipeBySlug (select recipe_steps(step,position)),
 * admin actions.ts và lib/recipes/database.ts (RecipeStepRow)
 * đều cần nó — seed chạy trong 1 transaction nên thiếu bảng là
 * rollback toàn bộ DB.
 *
 * Schema khớp seed: chỉ dùng (recipe_id, position, step);
 * id là identity để khớp kiểu RecipeStepRow trong database.ts.
 *
 * Quyền: đọc công khai, chỉ admin (kit.is_admin()) được ghi.
 * -------------------------------------------------------
 */

-- ─── recipe_steps (các bước thực hiện của từng công thức) ───
create table if not exists public.recipe_steps
(
    id        bigint generated by default as identity,
    recipe_id bigint not null references public.recipes (id) on delete cascade,
    position  integer not null,
    step      text not null,
    primary key (recipe_id, position)
);

comment on table public.recipe_steps is 'Các bước thực hiện của từng công thức, theo thứ tự position';

-- ─── Index ───
create index if not exists recipe_steps_recipe_id_idx on public.recipe_steps (recipe_id);

-- ─── RLS: đọc công khai, chỉ admin được ghi ───
alter table public.recipe_steps enable row level security;

drop policy if exists recipe_steps_read on public.recipe_steps;
create policy recipe_steps_read on public.recipe_steps
    for select
    to anon, authenticated
    using (true);

drop policy if exists recipe_steps_admin_write on public.recipe_steps;
create policy recipe_steps_admin_write on public.recipe_steps
    for all
    to authenticated
    using (kit.is_admin())
    with check (kit.is_admin());

-- ─── Quyền cột ───
grant select on public.recipe_steps to anon, authenticated, service_role;
grant select, insert, update, delete on public.recipe_steps to authenticated, service_role;
